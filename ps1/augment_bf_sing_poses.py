#!/usr/bin/env python3
"""Add one sampled BF singing pose per direction to the reusable W1 atlas.

The source conversion is intentionally narrow: it reuses the pinned BF atlas
and the already generated BF palette, patches the existing second pose to a
middle frame, and writes a final-frame pose into free texels on the same page.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

from convert_bopeebo_visuals import atlas_frames, extract_sparrow_frame, quantize


FRAME_W = 52
FRAME_H = 52
PAGE_BYTES = 256 * 256
NEW_POSE_XY = ((52, 204), (104, 204), (156, 204), (204, 204))
DIRECTIONS = ("left", "down", "up", "right")


def palette_from_header(header: str) -> list[tuple[int, int, int]]:
    match = re.search(
        r"static const uint16_t bopeebo_visual_palette_bf8\[256\] = \{(.*?)\};",
        header,
        re.S,
    )
    if not match:
        raise ValueError("generated header has no BF 8bpp palette")
    values = [int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{4})", match.group(1))]
    if len(values) != 256 or values[0] != 0:
        raise ValueError("unexpected BF palette shape")
    colors: list[tuple[int, int, int]] = []
    for value in values[1:]:
        colors.append(tuple((((value >> shift) & 31) << 3) | (((value >> shift) & 31) >> 2)
                            for shift in (0, 5, 10)))
    return colors


def frames_from_header(header: str) -> tuple[list[tuple[int, int, int, int, int, int]], dict[str, int]]:
    match = re.search(
        r"static const BopeeboVisualFrame bopeebo_visual_frames\[.*?\] = \{(.*?)\n\};",
        header,
        re.S,
    )
    if not match:
        raise ValueError("generated header has no visual frame table")
    rows = re.findall(r"\{([^}]+)\}, /\* ([^*]+) \*/", match.group(1))
    frames: list[tuple[int, int, int, int, int, int]] = []
    names: dict[str, int] = {}
    for index, (values, name) in enumerate(rows):
        fields = tuple(int(value.strip()) for value in values.split(",")[:6])
        if len(fields) != 6:
            raise ValueError(f"malformed frame descriptor: {name}")
        frames.append(fields)  # page, palette, u, v, w, h
        names[name.strip()] = index
    return frames, names


def paste_indexed(page: bytearray, x: int, y: int, width: int, height: int,
                  pixels: bytearray, stride: int) -> None:
    if width <= 0 or height <= 0 or x < 0 or y < 0 or x + width > 256 or y + height > 256:
        raise ValueError(f"BF pose rectangle exceeds texture page: {x},{y},{width},{height}")
    for row in range(height):
        source = pixels[row * stride:row * stride + width]
        page[(y + row) * 256 + x:(y + row) * 256 + x + width] = source


def write_header(path: pathlib.Path, page: int, palette: int,
                 coordinates: tuple[tuple[int, int], ...]) -> None:
    lines = [
        "/* Generated by augment_bf_sing_poses.py; do not edit. */",
        "#ifndef BF_SING_POSE_DATA_H",
        "#define BF_SING_POSE_DATA_H",
        "#define BOPEEBO_BF_SING_EXTRA_COUNT 4u",
        "static const BopeeboVisualFrame bopeebo_bf_sing_extra_frames[BOPEEBO_BF_SING_EXTRA_COUNT] = {",
    ]
    for x, y in coordinates:
        lines.append(f"\t{{{page}u, {palette}u, {x}u, {y}u, 52u, 52u, 0, 0, 0}},")
    lines.extend(("};", "#endif", ""))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="ascii")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--assets", required=True, type=pathlib.Path)
    parser.add_argument("--ffmpeg", required=True)
    parser.add_argument("--base-header", required=True, type=pathlib.Path)
    parser.add_argument("--base-scene", required=True, type=pathlib.Path)
    parser.add_argument("--output-header", required=True, type=pathlib.Path)
    parser.add_argument("--output-scene", required=True, type=pathlib.Path)
    args = parser.parse_args()

    header = args.base_header.read_text(encoding="ascii")
    palette = palette_from_header(header)
    frame_table, frame_names = frames_from_header(header)
    base_scene = bytearray(args.base_scene.read_bytes())
    bf_groups = atlas_frames(args.assets / "shared/images/characters/BOYFRIEND.xml")
    bf_png = args.assets / "shared/images/characters/BOYFRIEND.png"
    extra_coords = NEW_POSE_XY
    page_indices: set[int] = set()
    palette_indices: set[int] = set()

    if len(base_scene) < 9 * PAGE_BYTES:
        raise ValueError("base Week 1 scene is shorter than its 8bpp page table")

    for lane, direction in enumerate(DIRECTIONS):
        prefix = f"BF NOTE {direction.upper()}"
        frames = bf_groups.get(prefix, [])
        if len(frames) < 3:
            raise ValueError(f"BF {direction} animation has fewer than three atlas frames")
        first_pose_index = frame_names.get(f"bf_{direction}_0")
        middle_pose_index = frame_names.get(f"bf_{direction}_1")
        if first_pose_index is None or middle_pose_index is None:
            raise ValueError(f"base header lacks BF {direction} pose descriptors")
        first = frame_table[first_pose_index]
        middle = frame_table[middle_pose_index]
        if first[0] != middle[0] or first[1] != 2 or middle[1] != 2:
            raise ValueError(f"BF {direction} poses do not share the expected 8bpp CLUT/page")
        page_indices.add(first[0])
        palette_indices.add(first[1])

        # Keep the first source pose, replace the adjacent second pose with a
        # midpoint pose, and add the final source pose as the third sample.
        midpoint = (len(frames) - 1) // 2
        final = len(frames) - 1
        page_offset = first[0] * PAGE_BYTES
        for source_index, (u, v, w, h) in ((midpoint, (middle[2], middle[3], middle[4], middle[5])),
                                           (final, extra_coords[lane] + (FRAME_W, FRAME_H))):
            if (w, h) != (FRAME_W, FRAME_H):
                raise ValueError(f"unexpected BF {direction} frame dimensions: {w}x{h}")
            rgba = extract_sparrow_frame(args.ffmpeg, bf_png, frames[source_index], (FRAME_W, FRAME_H))
            indexed = quantize(rgba, palette)
            page = bytearray(base_scene[page_offset:page_offset + PAGE_BYTES])
            paste_indexed(page, u, v, FRAME_W, FRAME_H, indexed, FRAME_W)
            base_scene[page_offset:page_offset + PAGE_BYTES] = page

    if len(page_indices) != 1 or len(palette_indices) != 1:
        raise ValueError("BF singing poses do not share one texture page and CLUT")
    page_index = next(iter(page_indices))
    palette_index = next(iter(palette_indices))
    if page_index != 7:
        raise ValueError(f"expected BF atlas on page 7, found page {page_index}")

    args.output_scene.parent.mkdir(parents=True, exist_ok=True)
    args.output_scene.write_bytes(base_scene)
    write_header(args.output_header, page_index, palette_index, extra_coords)
    print("BF sing poses: four directions, three sampled poses each (source start/middle/end)")
    print(f"Patched only W1 8bpp page {page_index}; scene size remains {len(base_scene)} bytes")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # pragma: no cover - CLI diagnostic
        print(f"BF pose augmentation failed: {exc}", file=sys.stderr)
        raise SystemExit(1)
