#!/usr/bin/env python3
"""Copy the existing indexed BF frames into free Week 2 page space.

Week 2 replaces all nine shared 8bpp VRAM pages while its scene is active.
This postprocessor preserves the already-converted pixels and CLUTs, placing
the BF idle/sing cels and sampled sing extras in empty bottom strips of the
Week 2 character pages. It emits matching descriptors for the playable build.
"""

from __future__ import annotations

import argparse
import pathlib
import re


PAGE_SIDE = 256
PAGE_BYTES = PAGE_SIDE * PAGE_SIDE
FRAME_SIDE = 52
BF_PAGE = 7
BF_PALETTE = 2
W2_SLOT_Y = 204
W2_SLOT_XS = (0, 52, 104, 156)


def parse_visuals(text: str) -> tuple[dict[str, dict[str, int]], dict[str, int]]:
    match = re.search(
        r"static const BopeeboVisualFrame bopeebo_visual_frames\[.*?\] = \{(.*?)\n\};",
        text,
        re.S,
    )
    if not match:
        raise ValueError("visual header has no frame table")
    frames: dict[str, dict[str, int]] = {}
    for row, name in re.findall(r"\{([^}]+)\}, /\* ([^*]+) \*/", match.group(1)):
        values = [int(value.strip()) for value in row.split(",")[:6]]
        if len(values) != 6:
            raise ValueError(f"malformed visual descriptor {name}")
        frames[name.strip()] = dict(zip(("page", "palette", "u", "v", "w", "h"), values))
    ids = {
        name: int(value)
        for name, value in re.findall(r"^#define VIS_([A-Z0-9_]+) (\d+)u$", text, re.M)
    }
    return frames, ids


def parse_page_slots(text: str, count: int) -> list[int]:
    match = re.search(r"bopeebo_week2_page_slots\[BOPEEBO_WEEK2_PAGE_COUNT\] = \{([^}]+)\}", text)
    if not match:
        raise ValueError("visual header has no Week 2 VRAM page map")
    slots = [int(value) for value in re.findall(r"\d+", match.group(1))]
    if len(slots) != count:
        raise ValueError(f"Week 2 page map has {len(slots)} slots, expected {count}")
    return slots


def parse_extra_frames(text: str) -> list[dict[str, int]]:
    match = re.search(
        r"bopeebo_bf_sing_extra_frames\[BOPEEBO_BF_SING_EXTRA_COUNT\] = \{(.*?)\n\};",
        text,
        re.S,
    )
    if not match:
        raise ValueError("BF sampled singing pose header is missing")
    rows = []
    for row in re.findall(r"\{([^}]+)\}", match.group(1)):
        values = [int(value.strip().rstrip("u")) for value in row.split(",")[:6]]
        if len(values) != 6:
            raise ValueError("malformed BF sampled singing pose descriptor")
        rows.append(dict(zip(("page", "palette", "u", "v", "w", "h"), values)))
    return rows


def parse_count(text: str, name: str) -> int:
    match = re.search(rf"^#define {name} (\d+)u$", text, re.M)
    if not match:
        raise ValueError(f"missing {name}")
    return int(match.group(1))


def extract_rect(scene: bytes, frame: dict[str, int], label: str) -> bytes:
    if frame["page"] != BF_PAGE or frame["palette"] != BF_PALETTE:
        raise ValueError(f"{label} is not on the expected BF page/CLUT")
    if (frame["w"], frame["h"]) != (FRAME_SIDE, FRAME_SIDE):
        raise ValueError(f"{label} has unexpected size {frame['w']}x{frame['h']}")
    start = frame["page"] * PAGE_BYTES
    if len(scene) < start + PAGE_BYTES:
        raise ValueError("Week 1 source scene is missing BF texture page 7")
    page = scene[start:start + PAGE_BYTES]
    return b"".join(
        page[(frame["v"] + y) * PAGE_SIDE + frame["u"]:
             (frame["v"] + y) * PAGE_SIDE + frame["u"] + FRAME_SIDE]
        for y in range(FRAME_SIDE)
    )


def write_rect(scene: bytearray, package_page: int, x: int, y: int, pixels: bytes) -> None:
    start = package_page * PAGE_BYTES
    for row in range(FRAME_SIDE):
        src = row * FRAME_SIDE
        dst = start + (y + row) * PAGE_SIDE + x
        scene[dst:dst + FRAME_SIDE] = pixels[src:src + FRAME_SIDE]


def read_rect(scene: bytes, package_page: int, x: int, y: int) -> bytes:
    start = package_page * PAGE_BYTES
    return b"".join(
        scene[start + (y + row) * PAGE_SIDE + x:
              start + (y + row) * PAGE_SIDE + x + FRAME_SIDE]
        for row in range(FRAME_SIDE)
    )


def overlay_header(core: list[tuple[str, int, dict[str, int]]],
                   extras: list[dict[str, int]], page_slots: list[int]) -> str:
    lines = [
        "/* Generated by relocate_week2_bf_atlas.py; do not edit. */",
        "#ifndef WEEK2_BF_OVERLAY_DATA_H",
        "#define WEEK2_BF_OVERLAY_DATA_H",
        f"#define BOPEEBO_WEEK2_BF_OVERLAY_COUNT {len(core)}u",
        "static const uint16_t bopeebo_week2_bf_source_frames[BOPEEBO_WEEK2_BF_OVERLAY_COUNT] = {",
        "\t" + ",".join(f"{frame_id}u" for _, frame_id, _ in core) + ",",
        "};",
        "static const BopeeboVisualFrame bopeebo_week2_bf_overlay_frames[BOPEEBO_WEEK2_BF_OVERLAY_COUNT] = {",
    ]
    for _, _, frame in core:
        lines.append(
            f"\t{{{page_slots[frame['page']]}u, {BF_PALETTE}u, {frame['u']}u, "
            f"{frame['v']}u, {FRAME_SIDE}u, {FRAME_SIDE}u, 0, 0, 0}},"
        )
    lines.extend(("};", "static const BopeeboVisualFrame "
        "bopeebo_week2_bf_sing_extra_frames[BOPEEBO_BF_SING_EXTRA_COUNT] = {"))
    for frame in extras:
        lines.append(
            f"\t{{{page_slots[frame['page']]}u, {BF_PALETTE}u, {frame['u']}u, "
            f"{frame['v']}u, {FRAME_SIDE}u, {FRAME_SIDE}u, 0, 0, 0}},"
        )
    lines.extend(("};", "#endif", ""))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--visual-header", type=pathlib.Path, required=True)
    parser.add_argument("--bf-pose-header", type=pathlib.Path, required=True)
    parser.add_argument("--week1-scene", type=pathlib.Path, required=True)
    parser.add_argument("--week2-scene", type=pathlib.Path, required=True)
    parser.add_argument("--output-header", type=pathlib.Path, required=True)
    parser.add_argument("--output-scene", type=pathlib.Path, required=True)
    args = parser.parse_args()

    header = args.visual_header.read_text(encoding="ascii")
    frames, frame_ids = parse_visuals(header)
    page_count = parse_count(header, "BOPEEBO_WEEK2_PAGE_COUNT")
    stage_count = parse_count(header, "BOPEEBO_WEEK2_STAGE_PAGE_COUNT")
    slots = parse_page_slots(header, page_count)
    if page_count > 9 or stage_count != 2:
        raise ValueError("unexpected Week 2 page layout; expected two stage pages and at most nine total")

    core_names = [name for name in frames if re.fullmatch(r"bf_idle_\d+", name)]
    core_names += [f"bf_{direction}_{pose}" for direction in ("left", "down", "up", "right")
                   for pose in (0, 1)]
    if len(core_names) != 13 or any(name not in frames for name in core_names):
        raise ValueError(f"expected 13 BF idle/singing atlas frames, found {len(core_names)}")
    for name in core_names:
        frame = frames[name]
        if frame["page"] != BF_PAGE or frame["palette"] != BF_PALETTE or \
                (frame["w"], frame["h"]) != (FRAME_SIDE, FRAME_SIDE):
            raise ValueError(f"{name} is not the expected BF 52x52 page-7/CLUT-2 frame")
        if f"BF_{name[3:].upper()}" not in frame_ids:
            raise ValueError(f"visual header has no frame index for {name}")

    extra_frames = parse_extra_frames(args.bf_pose_header.read_text(encoding="ascii"))
    if len(extra_frames) != 4:
        raise ValueError(f"expected four sampled BF singing extras, found {len(extra_frames)}")

    scene1 = args.week1_scene.read_bytes()
    scene2 = bytearray(args.week2_scene.read_bytes())
    if len(scene2) != page_count * PAGE_BYTES + 512:
        raise ValueError("Week 2 scene size does not match its page-count and palette header")
    original_week2 = bytes(scene2)

    # Validate no existing Week 2 frame occupies the reserved bottom strip.
    page_occupancy: dict[int, list[tuple[int, int, int, int, str]]] = {}
    for name, frame in frames.items():
        if not name.startswith("week2_") or frame["page"] < stage_count:
            continue
        page_occupancy.setdefault(frame["page"], []).append(
            (frame["u"], frame["v"], frame["w"], frame["h"], name))

    destinations: list[tuple[int, int, int]] = []
    for package_page in range(stage_count, page_count):
        for x in W2_SLOT_XS:
            rect = (x, W2_SLOT_Y, FRAME_SIDE, FRAME_SIDE)
            collisions = [name for ox, oy, ow, oh, name in page_occupancy.get(package_page, [])
                          if rect[0] < ox + ow and ox < rect[0] + rect[2] and
                          rect[1] < oy + oh and oy < rect[1] + rect[3]]
            if collisions:
                continue
            destinations.append((package_page, x, W2_SLOT_Y))
    if len(destinations) < len(core_names) + len(extra_frames):
        raise ValueError(
            f"only {len(destinations)} collision-free bottom slots available; "
            f"{len(core_names) + len(extra_frames)} required")

    core_rows: list[tuple[str, int, dict[str, int]]] = []
    for index, name in enumerate(core_names):
        src = frames[name]
        pixels = extract_rect(scene1, src, name)
        package_page, x, y = destinations[index]
        write_rect(scene2, package_page, x, y, pixels)
        dest = {"page": package_page, "palette": BF_PALETTE, "u": x, "v": y,
                "w": FRAME_SIDE, "h": FRAME_SIDE}
        core_rows.append((name, frame_ids[f"BF_{name[3:].upper()}"], dest))

    relocated_extras: list[dict[str, int]] = []
    for index, src in enumerate(extra_frames):
        pixels = extract_rect(scene1, src, f"bf_sing_extra_{index}")
        package_page, x, y = destinations[len(core_names) + index]
        write_rect(scene2, package_page, x, y, pixels)
        relocated_extras.append({"page": package_page, "palette": BF_PALETTE,
                                 "u": x, "v": y, "w": FRAME_SIDE, "h": FRAME_SIDE})

    expected_scene = bytearray(original_week2)
    for index, (_, _, frame) in enumerate(core_rows):
        source = extract_rect(scene1, frames[core_names[index]], core_names[index])
        write_rect(expected_scene, frame["page"], frame["u"], frame["v"], source)
        if read_rect(bytes(scene2), frame["page"], frame["u"], frame["v"]) != source:
            raise AssertionError(f"relocated pixels changed for {core_names[index]}")
    for index, frame in enumerate(relocated_extras):
        source = extract_rect(scene1, extra_frames[index], f"bf_sing_extra_{index}")
        write_rect(expected_scene, frame["page"], frame["u"], frame["v"], source)
        if read_rect(bytes(scene2), frame["page"], frame["u"], frame["v"]) != source:
            raise AssertionError(f"relocated pixels changed for sampled pose {index}")
    if bytes(scene2) != bytes(expected_scene):
        raise AssertionError("Week 2 pages changed outside the allocated BF rectangles")
    if scene2[page_count * PAGE_BYTES:] != original_week2[page_count * PAGE_BYTES:]:
        raise AssertionError("Week 2 CLUT bytes changed")

    args.output_scene.parent.mkdir(parents=True, exist_ok=True)
    args.output_header.parent.mkdir(parents=True, exist_ok=True)
    args.output_scene.write_bytes(scene2)
    args.output_header.write_text(overlay_header(core_rows, relocated_extras, slots),
                                  encoding="ascii", newline="\n")
    print(f"Relocated {len(core_rows)} BF idle/sing frames and {len(relocated_extras)} sampled poses")
    print(f"Destination: Week 2 pages {stage_count}..{page_count - 1}, reserved y={W2_SLOT_Y}..255")
    print(f"Package size unchanged: {len(scene2)} bytes; all source indices and BF CLUT entries preserved")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
